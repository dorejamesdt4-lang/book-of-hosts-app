// ====================================================================
// THE GAME LOBBY (host) — loads the master script, runs the script
// check (engine/check.js), voices in advance what the chosen way of
// playing needs (real progress, stored for the Stage), shows which
// Player's Hand tabs are open, and starts the show.
//
//   Online:  Begin → stage.html (Rehearse → stage.html?mode=rehearse)
//   Theatre: Begin → theatre-stage.html in this tab (for the TV) and the
//            Host Console in its own window (for the laptop)
// ====================================================================

import {
  loadAll, pack as packFor, lsGet, lsSet, keys, prefs, openChannel, createPresence, playerName, spriteFor,
  registryEntry, el, fitBoard, pill
} from './common.js';
import { scriptCheck } from '../engine/check.js';
import { MODULES } from '../engine/minigames.js';
import { playModes, castInSeatOrder, roman } from '../engine/script.js';
import { speechItems, voiceFor } from '../engine/themes.js';
import { createVoiceBank } from './voice-bank.js';

const $ = (id) => document.getElementById(id);
fitBoard($('board'));

const PASS_ICON = '<svg width="18" height="18" viewBox="0 0 24 24" aria-hidden="true" style="flex-shrink: 0"><circle cx="12" cy="12" r="10" fill="none" stroke="#5AA8A0" stroke-width="2"></circle><path d="M7 12.5 L10.5 16 L17 9" fill="none" stroke="#5AA8A0" stroke-width="2.2" stroke-linecap="round" stroke-linejoin="round"></path></svg>';
const FAIL_ICON = '<svg width="18" height="18" viewBox="0 0 24 24" aria-hidden="true" style="flex-shrink: 0"><circle cx="12" cy="12" r="10" fill="none" stroke="#9E3B3B" stroke-width="2"></circle><path d="M8.5 8.5 L15.5 15.5 M15.5 8.5 L8.5 15.5" fill="none" stroke="#9E3B3B" stroke-width="2.2" stroke-linecap="round"></path></svg>';
const LINK_ICON = '<svg width="16" height="16" viewBox="0 0 24 24" aria-hidden="true"><path d="M10 14 a4 4 0 0 0 5.6 0 l3-3 a4 4 0 0 0-5.6-5.6 l-1 1 M14 10 a4 4 0 0 0-5.6 0 l-3 3 a4 4 0 0 0 5.6 5.6 l1-1" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round"></path></svg>';

const data = await loadAll();
const { game } = data;
const gamePack = packFor(data, game.game.theme);
const modes = playModes(game).filter((m) => m !== 'pdf');
let playMode = modes.includes(lsGet(keys.playMode, 'online')) ? lsGet(keys.playMode, 'online') : modes[0] || 'online';
let narration = lsGet(keys.narration, 'voice');
let selectedPack = packFor(data, lsGet(keys.rehearseTheme, game.game.theme));
const bank = createVoiceBank();
const ready = new Map(); // "<mode>:<pack>:<narration>" -> true once voiced

/* -------------------- master script card -------------------- */
$('gameTitle').textContent = game.game.title;
$('gameSource').textContent = (game.sample ? 'Sample game' : 'Generated by Ruby') + ' · Master Script v' + game.schema_version;
$('countActs').textContent = game.acts.length;
$('countBeats').textContent = game.beats.length;
$('countPlayers').textContent = game.cast.length;
$('countGames').textContent = game.beats.filter((b) => b.type === 'mini_game').length;

const results = scriptCheck({ game, minigames: data.minigames, modules: MODULES });
const checksPassed = results.every((r) => r.ok);
$('checkHeading').textContent = checksPassed ? 'SCRIPT CHECK PASSED' : 'SCRIPT CHECK FAILED';
$('checkHeading').style.color = checksPassed ? '#2E6E69' : '#9E3B3B';
results.forEach((r) => {
  const row = el('div', { style: 'display: flex; gap: 10px; align-items: flex-start' });
  row.insertAdjacentHTML('afterbegin', r.ok ? PASS_ICON : FAIL_ICON);
  const text = el('div', { style: 'display: flex; flex-direction: column; gap: 2px' }, r.label);
  if (!r.ok && r.detail) text.appendChild(el('div', { style: 'font-size: 14px; font-style: italic; color: #9E3B3B' }, r.detail));
  row.appendChild(text);
  $('checkList').appendChild(row);
});

/* -------------------- running order -------------------- */
$('runningOrder').style.gridTemplateColumns = 'repeat(' + game.acts.length + ', minmax(0, 1fr))';
game.acts.forEach((act) => {
  const beats = game.beats.filter((b) => b.act === act.id);
  const games = beats.filter((b) => b.type === 'mini_game').length;
  const secrets = beats.filter((b) => b.type === 'private_reveal').length;
  const parts = [beats.length + ' beats'];
  if (games) parts.push(games + (games === 1 ? ' mini-game' : ' mini-games'));
  if (secrets) parts.push(secrets + (secrets === 1 ? ' secret' : ' secrets'));
  if (beats.some((b) => b.type === 'vote')) parts.push('vote');
  $('runningOrder').appendChild(el('div', { style: 'display: flex; flex-direction: column; gap: 6px; padding: 14px; border: 1px solid #1E3A3A; border-radius: 8px' },
    el('div', { style: "font-family: 'Cinzel', serif; font-weight: 700; font-size: 16px; color: #D9A441" }, 'Act ' + roman(act.number) + ' · ' + act.title),
    el('div', { style: 'font-size: 15px; color: #A9C9C4' }, parts.join(' · '))));
});

/* -------------------- seats -------------------- */
const presence = createPresence();
openChannel((msg) => {
  if (msg.type === 'hello' && msg.seat) { presence.hello(msg.seat); renderStatuses(); }
  if (msg.type === 'bye' && msg.seat) { presence.bye(msg.seat); renderStatuses(); }
}).post({ type: 'ping' });

const seatEls = new Map();

function renderSeats() {
  $('seatGrid').innerHTML = '';
  seatEls.clear();
  castInSeatOrder(game).forEach((c) => {
    const seat = c.character;
    const sprite = registryEntry(data, spriteFor(data, seat));
    const thumb = sprite && sprite.thumbnail
      ? el('img', { class: 'ls-thumb', src: '../' + sprite.thumbnail, alt: '', style: 'width: 56px; height: 56px; flex-shrink: 0' })
      : el('div', { style: 'width: 56px; height: 56px' });
    const player = el('div', { style: 'font-size: 17px; color: #EDE6D6' });
    const status = el('div', { style: "font-family: 'Silkscreen', monospace; font-size: 10px" });
    // The host's re-cast (online only: in theatre, people read their own lines).
    const voice = el('select', { 'aria-label': 'Voice for ' + c.title, style: "flex-grow: 1; min-width: 0; height: 40px; border: 1px solid #2A4A4A; border-radius: 8px; background: #0B1620; color: #EDE6D6; font-family: 'Cardo', serif; font-size: 14px; padding: 0 8px" });
    selectedPack.voice_pool.forEach((v) => voice.appendChild(el('option', { value: v.id }, v.label)));
    voice.value = voiceFor(game, selectedPack, seat, prefs);
    voice.hidden = playMode === 'theatre';
    voice.addEventListener('change', () => {
      lsSet(keys.recast(selectedPack.id, seat), voice.value);
      ready.clear();
      prepareVoices();
    });
    const handLink = el('a', { href: 'hand.html?seat=' + encodeURIComponent(seat), target: '_blank', rel: 'noopener', 'aria-label': 'Open ' + c.title + "'s Player's Hand", style: 'flex-shrink: 0; font-size: 14px; font-style: italic; white-space: nowrap' }, 'Open Hand ↗');
    const invite = el('button', { type: 'button', class: 'pbtn', style: "height: 44px; padding: 0 14px; border: 1px solid #D9A441; border-radius: 6px; background: transparent; color: #D9A441; font-family: 'Cinzel', serif; font-size: 12px; letter-spacing: 1px; display: flex; align-items: center; gap: 8px; cursor: pointer; flex-shrink: 0" });
    invite.insertAdjacentHTML('afterbegin', LINK_ICON);
    invite.appendChild(document.createTextNode('INVITE'));
    invite.addEventListener('click', () => {
      window.open('invite.html?seat=' + encodeURIComponent(seat), '_blank', 'noopener');
      window.open('hand.html?seat=' + encodeURIComponent(seat), '_blank', 'noopener');
    });
    const card = el('div', { class: 'seat', style: 'display: flex; flex-direction: column; gap: 12px; padding: 14px 16px; background: #0F1E28; border: 1px solid #2A4A4A; border-radius: 12px' },
      el('div', { style: 'display: flex; align-items: center; gap: 16px' },
        el('div', { style: 'width: 72px; height: 80px; flex-shrink: 0; box-sizing: border-box; border-radius: 36px 36px 6px 6px; background: #0B1620; border: 1.5px solid #B8923E; display: flex; align-items: flex-end; justify-content: center; padding-bottom: 6px; overflow: hidden' }, thumb),
        el('div', { style: 'display: flex; flex-direction: column; gap: 4px; flex-grow: 1; min-width: 0' },
          el('div', { style: "font-family: 'Cinzel', serif; font-weight: 700; font-size: 15px; color: #D9A441" }, c.title),
          player, status),
        invite),
      // Not on the mockup: the host's re-cast and a link to this seat's Hand.
      el('div', { style: 'display: flex; align-items: center; justify-content: space-between; gap: 12px' }, voice, handLink));
    $('seatGrid').appendChild(card);
    seatEls.set(seat, { player, status, invite });
  });
  renderStatuses();
}

function renderStatuses() {
  let seated = 0;
  seatEls.forEach((els, seat) => {
    const name = playerName(seat);
    const open = presence.open(seat);
    if (open) seated += 1;
    els.player.textContent = name || 'No player yet';
    if (open) { els.status.textContent = 'HAND OPEN'; els.status.style.color = '#5AA8A0'; }
    else if (name) { els.status.textContent = 'HAND CLOSED'; els.status.style.color = '#D9A441'; }
    else { els.status.textContent = 'OPEN SEAT'; els.status.style.color = '#8FA5A3'; }
    els.invite.hidden = !!name;
  });
  $('seatedCount').textContent = seated + ' of ' + game.cast.length + ' seated';
}
setInterval(renderStatuses, 1000);
window.addEventListener('storage', () => renderSeats());

/* -------------------- play mode, narration, rehearsal theme -------------------- */
function renderSwitches() {
  const labels = { online: 'ONLINE', theatre: 'THEATRE' };
  $('modeSwitch').innerHTML = '';
  modes.forEach((m) => $('modeSwitch').appendChild(pill(labels[m] || m.toUpperCase(), m === playMode, () => {
    playMode = m;
    lsSet(keys.playMode, m);
    refreshMode();
  })));
  $('narrationSwitch').innerHTML = '';
  [['voice', 'NARRATOR VOICE'], ['text', 'THE HOST READS IT']].forEach(([v, label]) => $('narrationSwitch').appendChild(pill(label, v === narration, () => {
    narration = v;
    lsSet(keys.narration, v);
    refreshMode();
  })));
  $('themeSwitch').innerHTML = '';
  data.themes.forEach((p) => $('themeSwitch').appendChild(pill(p.name.toUpperCase(), p.id === selectedPack.id, () => {
    selectedPack = p;
    lsSet(keys.rehearseTheme, p.id);
    refreshMode();
  })));
}

function refreshMode() {
  const theatre = playMode === 'theatre';
  if (theatre) selectedPack = gamePack;
  $('modeBadge').textContent = theatre ? 'IN PERSON · THEATRE' : 'ONLINE · NARRATOR ON';
  $('narrationRow').hidden = !theatre;
  $('rehearseRow').hidden = theatre;
  $('btnRehearse').hidden = theatre;
  $('btnPrint').textContent = theatre ? 'PRINT THEATRE SCRIPTS' : 'PRINT PDFS INSTEAD';
  renderSwitches();
  renderSeats();
  prepareVoices();
}

/* -------------------- voices, prepared in advance -------------------- */
const readyKey = (p) => playMode + ':' + p.id + ':' + (playMode === 'theatre' ? narration : '-');

function showProgress(p, done, total, modelPct) {
  if (p.id !== selectedPack.id) return;
  $('prepCount').textContent = done + ' / ' + total;
  $('prepBar').style.width = (total ? (done / total) * 100 : 0) + '%';
  const finished = total === 0 || done >= total;
  $('prepText').textContent = finished ? 'The voices are ready.' : 'The Scribe is inking the voices…';
  $('prepNote').textContent = modelPct !== null && !finished
    ? 'Loading the voice model… ' + Math.floor(modelPct) + '%'
    : playMode === 'theatre'
      ? (narration === 'voice' ? 'Narration and stand-in lines are prepared before the show.' : 'You read the narration; stand-in lines are prepared before the show.')
      : 'Narration is prepared before the show, so there are no pauses mid-scene.';
}

function updateButtons() {
  $('btnBegin').disabled = !checksPassed || !ready.get(readyKey(gamePack));
  $('btnRehearse').disabled = !checksPassed || !ready.get(readyKey(selectedPack));
}

let prepRun = 0;
async function prepareVoices() {
  const run = ++prepRun;
  if (run > 1) bank.cancel();
  updateButtons();
  const packs = selectedPack.id === gamePack.id ? [gamePack] : [gamePack, selectedPack];
  for (const p of packs) {
    if (run !== prepRun) return;
    const items = speechItems(game, p, prefs, { mode: playMode === 'theatre' ? 'theatre' : 'online', narration });
    try {
      await bank.prepare(items, (done, total, pct) => {
        if (run !== prepRun) return;
        showProgress(p, done, total, pct);
        if (done >= total) { ready.set(readyKey(p), true); updateButtons(); }
      });
      if (!items.length) { ready.set(readyKey(p), true); showProgress(p, 0, 0, null); updateButtons(); }
    } catch (err) {
      console.error('Could not voice the script', err);
      if (p.id === selectedPack.id) {
        $('prepText').textContent = 'The voices could not be prepared.';
        $('prepNote').textContent = 'Check your connection, then reload the Lobby to try again.';
      }
      return;
    }
  }
}

